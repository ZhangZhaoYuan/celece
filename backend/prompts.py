def get_prompt(category_name: str) -> str:
    """根据分类名获取提示词"""
    config = CATEGORY_CONFIG.get(category_name)
    if not config:
        prompt = _get_generic_prompt(category_name)
    else:
        template = config.get("template")
        template_args = config.get("template_args", {})
        if template:
            try:
                prompt = template.format(**template_args)
            except KeyError:
                prompt = template
        else:
            prompt = _get_generic_prompt(category_name)
    
    # 在所有提示词后面加上强制输出格式说明
    prompt += """

⚠️ 重要：请严格按照上面的三段式【详细描述】【关键标签】【适用客户】输出。
三段都必须有内容，【适用客户】必须输出3个优先级，哪怕你认为不够3个也要写出。
标签用英文逗号分隔，不要用JSON格式，不要用列表格式。"""
    return prompt


def get_category_config(category_name: str) -> dict:
    """获取分类配置"""
    return CATEGORY_CONFIG.get(category_name, {})


def get_default_scenarios(category_name: str) -> list:
    """获取分类的默认适用场景"""
    config = CATEGORY_CONFIG.get(category_name, {})
    return config.get("default_scenarios", [])


def get_default_tags(category_name: str) -> list:
    """获取分类的默认标签前缀"""
    config = CATEGORY_CONFIG.get(category_name, {})
    return config.get("tag_keys", ["用途_通用"])


